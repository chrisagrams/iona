"""Tiny end-to-end runs of the real entry points, each as `python -m msdelta.<path>`.

Opt-in (marker `e2e`): `pytest tests/e2e --e2e`, or on one debug node
`qsub pbs/run_e2e.pbs`. Each test drives a subprocess exactly as a PBS script would,
on synthetic data generated by tests/e2e/synth.py, with a 2-layer hidden-32 model and
~10-20 optimizer steps. They check the wiring between stages -- argument parsing,
data loading from local paths, checkpoint layout, resume, the files each stage hands
the next -- and never model quality.

The chain: pretraining -> (contrastive, denoise, alignment) -> grouped-retrieval eval
over the contrastive encoder. Downstream stages use module-scoped fixtures, so a
failure in pretraining shows up as errors in everything that needs its checkpoint.
"""

from __future__ import annotations

import json
import math
import os
import subprocess
import sys
from pathlib import Path

import numpy as np
import pytest

from tests.e2e import synth

pytestmark = pytest.mark.e2e

REPO = Path(__file__).resolve().parents[2]
MAX_PEAKS = 64


def run_module(module: str, args: list[str], log: Path, timeout: int = 900) -> str:
    """Run `python -m module args`, tee'd to `log`; fail with the tail on non-zero exit.

    `datasets.load_dataset(<local dir>)` writes an arrow cache; it goes next to the log,
    never into the shared HF_HOME.
    """
    env = dict(os.environ)
    env.setdefault("WANDB_MODE", "disabled")
    env["HF_DATASETS_CACHE"] = str(log.parent.parent / "hf-datasets-cache")
    env["PYTHONPATH"] = str(REPO) + (os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else "")
    proc = subprocess.run([sys.executable, "-m", module, *map(str, args)], cwd=REPO, env=env,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                          timeout=timeout)
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(proc.stdout)
    if proc.returncode != 0:
        tail = "\n".join(proc.stdout.splitlines()[-60:])
        pytest.fail(f"{module} exited {proc.returncode}; log {log}\n{tail}")
    return proc.stdout


def train_log(run_dir: Path) -> list[dict]:
    """log_history of the newest checkpoint in run_dir (Trainer writes it there)."""
    ckpts = sorted(run_dir.glob("checkpoint-*"), key=lambda p: int(p.name.split("-")[1]))
    assert ckpts, f"no checkpoint under {run_dir}"
    return json.loads((ckpts[-1] / "trainer_state.json").read_text())["log_history"]


def loss_steps(history: list[dict]) -> list[int]:
    return [h["step"] for h in history if "loss" in h]


def common_training_args(out: Path, steps: int, save_steps: int) -> list[str]:
    return ["--output_dir", out, "--max_steps", steps, "--save_strategy", "steps",
            "--save_steps", save_steps, "--logging_steps", 1, "--report_to", "none",
            "--remove_unused_columns", "false", "--dataloader_num_workers", 0,
            "--seed", 0, "--warmup_steps", 0]


def assert_resumed(first: Path, resumed: Path, n_first: int, n_total: int) -> None:
    """The resumed run picks up at n_first+1 and ends at n_total, every step once.

    Identical losses for steps 1..n_first alone would not prove a resume: a run that
    silently IGNORED --resume_from_checkpoint (the bug the entry points guard against)
    retrains them deterministically. It would also save checkpoint-n_first again, so
    the resumed directory must not have one. Losses after the resume point are close to
    the uninterrupted run's but not identical (the sampler's epoch state is not
    checkpointed), so only finiteness is asserted there.
    """
    assert not (resumed / f"checkpoint-{n_first}").exists(), \
        "resumed run re-saved the resume point: it restarted from step 0"
    steps = loss_steps(train_log(resumed))
    assert steps == list(range(1, n_total + 1)), f"resumed step sequence {steps}"
    state = json.loads((resumed / f"checkpoint-{n_total}" / "trainer_state.json").read_text())
    assert state["global_step"] == n_total
    # Steps 1..n_first come from the checkpoint's own history, not from retraining them.
    original = {h["step"]: h["loss"] for h in train_log(first) if "loss" in h}
    replayed = {h["step"]: h["loss"] for h in train_log(resumed) if "loss" in h}
    for s in range(1, n_first + 1):
        assert replayed[s] == original[s]
    for s in range(n_first + 1, n_total + 1):
        assert math.isfinite(replayed[s])


