# ------------------------------------------------------------------------------- tests

def test_pretraining(pretrained):
    """(a) ~20 steps on 64 spectra: loss finite and falling; checkpoint reloads."""
    import torch

    from msdelta.models.modeling_msdelta import MSDeltaForPreTraining
    history = train_log(pretrained)
    losses = [h["loss"] for h in history if "loss" in h]
    assert len(losses) == 20 and all(math.isfinite(x) for x in losses)
    assert np.mean(losses[-5:]) < np.mean(losses[:5]), losses
    assert any("eval_loss" in h and math.isfinite(h["eval_loss"]) for h in history)
    final = MSDeltaForPreTraining.from_pretrained(str(pretrained / "final"))
    ckpt = MSDeltaForPreTraining.from_pretrained(str(pretrained / "checkpoint-20"))
    assert final.config.num_hidden_layers == 2 and final.config.hidden_size == 32
    for (name, a), (_, b) in zip(final.state_dict().items(), ckpt.state_dict().items()):
        assert torch.equal(a, b), name
    assert (pretrained / "final" / "preprocessor_config.json").exists()


def test_contrastive_and_resume(work, data, pretrained, contrastive):
    """(b) current recipe for 10 steps, then resume from checkpoint-5 to step 10."""
    from msdelta.models.modeling_msdelta import MSDeltaForPreTraining
    assert (contrastive / "final" / "config.json").exists()
    MSDeltaForPreTraining.from_pretrained(str(contrastive / "final"))
    # SaveEncoderCallback: every checkpoint carries a loadable encoder.
    MSDeltaForPreTraining.from_pretrained(str(contrastive / "checkpoint-5" / "encoder"))
    losses = [h["loss"] for h in train_log(contrastive) if "loss" in h]
    assert len(losses) == 10 and all(math.isfinite(x) for x in losses)
    assert (contrastive / "separation_results.json").exists()

    resumed = work / "contrastive-resumed"
    run_module("msdelta.finetuning.contrastive.finetune_contrastive",
               contrastive_args(pretrained, data, resumed)
               + ["--resume_from_checkpoint", contrastive / "checkpoint-5"],
               work / "logs" / "contrastive-resumed.log")
    assert_resumed(contrastive, resumed, 5, 10)


