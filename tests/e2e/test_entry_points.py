def test_denoise_and_resume(work, data, pretrained):
    """(c) 10 steps + validation/test eval: AUROC/F1 finite; resume from checkpoint-5."""
    out = work / "denoise"
    run_module("msdelta.finetuning.denoise.finetune_denoise",
               denoise_args(pretrained, data, out), work / "logs" / "denoise.log")
